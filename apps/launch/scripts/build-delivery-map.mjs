#!/usr/bin/env node
/**
 * Regenerates src/lib/geo/delivery-map.ts: SVG path data for the Southern
 * California counties drawn on the delivery map.
 *
 * Source: U.S. Census Bureau TIGERweb, Generalized ACS 2023 "Counties 500K"
 * cartographic boundaries (shoreline-clipped, public domain).
 *
 *   node scripts/build-delivery-map.mjs
 */
import { writeFile } from "node:fs/promises";
import path from "node:path";

const COUNTIES = {
  "06037": "losAngeles",
  "06059": "orange",
  "06111": "ventura",
  "06071": "sanBernardino",
  "06065": "riverside",
  "06073": "sanDiego",
  "06029": "kern",
};

/** Map frame (degrees). Covers mainland LA + Orange County and Catalina. */
const BOUNDS = { west: -119.05, east: -117.25, south: 33.25, north: 34.9 };
const WIDTH = 1000;
const LAT0 = ((BOUNDS.north + BOUNDS.south) / 2) * (Math.PI / 180);
const X_SCALE = WIDTH / ((BOUNDS.east - BOUNDS.west) * Math.cos(LAT0));
const HEIGHT = Math.round((BOUNDS.north - BOUNDS.south) * X_SCALE);

const project = ([lon, lat]) => [
  +((lon - BOUNDS.west) * Math.cos(LAT0) * X_SCALE).toFixed(1),
  +((BOUNDS.north - lat) * X_SCALE).toFixed(1),
];

const url = new URL(
  "https://tigerweb.geo.census.gov/arcgis/rest/services/Generalized_ACS2023/State_County/MapServer/11/query",
);
url.search = new URLSearchParams({
  where: `GEOID IN (${Object.keys(COUNTIES).map((id) => `'${id}'`).join(",")})`,
  outFields: "GEOID,NAME",
  f: "geojson",
  outSR: "4326",
  maxAllowableOffset: "0.0015",
}).toString();

const response = await fetch(url);
if (!response.ok) throw new Error(`TIGERweb request failed: ${response.status}`);
const geojson = await response.json();

const paths = {};
for (const feature of geojson.features) {
  const key = COUNTIES[feature.properties.GEOID];
  const polygons =
    feature.geometry.type === "Polygon" ? [feature.geometry.coordinates] : feature.geometry.coordinates;
  paths[key] = polygons
    .map((rings) =>
      rings
        .map((ring) => {
          const points = ring.map(project);
          return `M${points.map(([x, y]) => `${x} ${y}`).join("L")}Z`;
        })
        .join(""),
    )
    .join("");
}

const kitchen = { lon: -118.187602, lat: 33.772621 };
const [kx, ky] = project([kitchen.lon, kitchen.lat]);
const radiusMiles = 20;
const radius = +((radiusMiles / 69.0) * X_SCALE).toFixed(1);

const file = `// Generated by scripts/build-delivery-map.mjs — do not edit by hand.
// Source: U.S. Census Bureau TIGERweb, Generalized ACS 2023 county cartographic boundaries (public domain).

export const DELIVERY_MAP = {
  width: ${WIDTH},
  height: ${HEIGHT},
  /** Projection used for every point: equirectangular, scaled at the frame's mid-latitude. */
  projection: { west: ${BOUNDS.west}, north: ${BOUNDS.north}, cosLat: ${Math.cos(LAT0).toFixed(6)}, scale: ${X_SCALE.toFixed(4)} },
  /** Soul Good kitchen, Long Beach (U.S. Census geocoder). */
  kitchen: { x: ${kx}, y: ${ky} },
  /** ${radiusMiles}-mile on-demand radius, in map units. */
  onDemandRadius: ${radius},
  counties: ${JSON.stringify(paths, null, 2)},
} as const;
`;

const out = path.join(import.meta.dirname, "..", "src", "lib", "geo", "delivery-map.ts");
await writeFile(out, file);
console.log(`Wrote ${out} (${WIDTH}×${HEIGHT}, radius ${radius})`);
